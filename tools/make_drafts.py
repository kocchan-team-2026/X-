def split_text(text: str) -> list[str]:
    chunks = text.split("§")
    for c in chunks:
        assert len(c) <= LIMIT, f"{len(c)}字: {c[:20]}"
    return chunks


JITTER_MIN = 25  # 基準の時刻から前後に最大25分ずらす
SLOTS = ["20:30", "22:30"]  # 夜に投稿(ドン底ちゃんは20〜23時が中心)


def main() -> None:
    for old in POSTS_DIR.glob("draft_*"):
        shutil.rmtree(old)
    for old in WORKS_DIR.glob("seller-*.json"):
        old.unlink()
    for old in WORKS_DIR.glob("post-*.json"):
        old.unlink()
    start = (datetime.now() + timedelta(days=1)).date()
    for n, (kind, full) in enumerate(DRAFTS, 1):
        chunks = split_text(full)
        text, thread = chunks[0], chunks[1:]
        seller = "雷鳥"
        wid = f"post-{n:02d}"
        sid = SELLERS[seller][0]
        reply = REPLIES[n - 1] + TAIL
        assert len(reply) <= 140
        day = start + timedelta(days=(n - 1) // 2)
        base = datetime.fromisoformat(f"{day}T{SLOTS[(n - 1) % 2]}")
        jitter = random.Random(n * 7919).randint(-JITTER_MIN, JITTER_MIN)  # 毎日同じ時刻にならないよう、ゆらぎを持たせる(再実行しても同じ値)
        planned = (base + timedelta(minutes=jitter)).isoformat(timespec="minutes")
        d = POSTS_DIR / f"draft_{n:02d}"
        d.mkdir(parents=True)
        (d / "meta.json").write_text(json.dumps({"work_id": wid, "tweet_id": f"draft{n:02d}",
                                                 "saved_at": datetime.now().isoformat(timespec="seconds")}), encoding="utf-8")
        tw = {"url": "", "id": f"draft{n:02d}", "text": text,
              "author": {"name": f"案{n:02d}・{kind}・{seller}", "screen_name": "draft"}}
        (d / "tweet.json").write_text(json.dumps(tw, ensure_ascii=False, indent=2), encoding="utf-8")
        (d / "text.md").write_text(text + "\n", encoding="utf-8")
        WORKS_DIR.mkdir(parents=True, exist_ok=True)
        write_json_atomic(WORKS_DIR / f"{wid}.json", {
            "urls": [], "affiliate": A8 + sid, "followup_text": reply, "planned_at": planned, "seller": seller, "kind": kind, "thread": thread})
    print(f"{len(DRAFTS)}件の投稿案を作りました(予定: {start} から1日2本)")


main()
